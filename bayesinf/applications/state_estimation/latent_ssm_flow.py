"""
LatentSSMFlow: Conditional Normalizing Flow with Linear Gaussian SSM latent dynamics
for full-sequence state estimation.

Architecture (state estimation):

    enc(y_{1:T}) ── cond_t ──┐
    x_{t-1}  ────────────────┤
                              │
    z_1 ~ N(0, P_inf)         │
    z_t = F z_{t-1} + G ε_t  flow⁻¹(·; cond_t, x_{t-1}) ──► x_t

Segmentation (seg_len > 0):
    - Trajectory split into ceil(T / seg_len) segments, retaining the final partial segment.
    - Within each segment: autoregressive x_{t-1} conditioning (scan over seg_len steps).
    - Across segments at inference: generated states are carried forward sequentially.
    - SSM prior restarts independently at each segment boundary (z_1 ~ N(0, P_inf)).
    - Segment boundary x_prev:
        * Training  — true state at the last step of the preceding segment.
        * Inference — generated state at the last step of the preceding segment.

Training — exact MLE via change of variables:
    x_prev_t       = true state at t-1 within segment
    z_t            = flow(x_t ; [cond_t, x_prev_t])
    log p(x_{1:T}) = Σ_segs [ Σ_t log|det J| + log p_SSM(z_{1:seg}) ]

Inference (posterior samples):
    z_{1:seg} ~ SSM prior  (per segment, independent)
    x_t = flow⁻¹(z_t; [cond_t, x_{t-1}])  (scan within each segment; generated boundary carried between segments)
    Boundary x_prev for segment s is generated by the previous decoded segment.
"""

import jax
import jax.numpy as jnp
import jax.random as jr
import equinox as eqx
from typing import Optional, Tuple

from bayesinf.applications.state_estimation.amortized_state_flow import (
    StateConditionEncoder,
)
from bayesinf.applications.state_estimation.pointwise_state_flow import (
    build_flow_transforms,
)
from bayesinf.models.flow_matching import VectorField as FlowMatchingVectorField
from bayesinf.models.normalizing_flow import ActNorm, RandomPermutation, MAFLayer


# ---------------------------------------------------------------------------
# Flow forward / inverse helpers  (single timestep)
# ---------------------------------------------------------------------------

def _flow_fwd_single(
    transforms: list,
    x:          jnp.ndarray,   # (d_x,)
    x_prev:     jnp.ndarray,   # (d_x,)
    cond:       jnp.ndarray,   # (d_out,)
) -> Tuple[jnp.ndarray, jnp.ndarray]:
    """x → z  (encoding). Returns (z, log|dz/dx|)."""
    combined_cond = jnp.concatenate([x_prev, cond])
    z_b  = x[None]
    ld_b = jnp.zeros((1,))
    for t in transforms:
        if isinstance(t, (ActNorm, RandomPermutation)):
            z_b, ldj = t(z_b, reverse=False)
        else:
            z_b, ldj = t(z_b, cond=combined_cond[None], reverse=False)
        ld_b = ld_b + ldj
    return z_b[0], ld_b[0]


def _flow_inv_single(
    transforms: list,
    z:          jnp.ndarray,   # (d_x,)
    x_prev:     jnp.ndarray,   # (d_x,)
    cond:       jnp.ndarray,   # (d_out,)
) -> Tuple[jnp.ndarray, jnp.ndarray]:
    """z → x  (decoding). Returns (x, log|dx/dz|)."""
    combined_cond = jnp.concatenate([x_prev, cond])
    x_b  = z[None]
    ld_b = jnp.zeros((1,))
    for t in reversed(transforms):
        if isinstance(t, (ActNorm, RandomPermutation)):
            x_b, ldj = t(x_b, reverse=True)
        else:
            x_b, ldj = t(x_b, cond=combined_cond[None], reverse=True)
        ld_b = ld_b + ldj
    return x_b[0], ld_b[0]


# ---------------------------------------------------------------------------
# LatentSSMFlow
# ---------------------------------------------------------------------------

class LatentSSMFlow(eqx.Module):
    """
    Linear Gaussian SSM in latent space + conditional normalizing flow decoder.

    Parameters
    ----------
    d_x          : state / data dimension
    d_y          : observation dimension (defaults to d_x if -1)
    d_u          : control input dimension (0 if unused)
    d_enc        : encoder internal hidden dim
    d_out        : flow conditioning dim (encoder output)
    seg_len      : segment length for parallel processing (0 = full sequence)
    encoder_type : 'gru' | 'transformer' | 'pointwise'
                   'pointwise' — each step t is conditioned only on (y_t, u_t)
                   via a small MLP; no future information leaks into cond_t.
                   Temporal context comes entirely from the SSM and x_{t-1}.
    flow_type    : 'realnvp' | 'nsf' | 'maf' | 'fm'
    n_coupling   : number of flow coupling blocks
    hidden_size  : MLP hidden width (flow)
    d_enc        : hidden width of the pointwise encoder MLP
    n_hidden     : MLP depth
    max_rho      : spectral radius cap on F
    """

    encoder:    object   # StateConditionEncoder  OR  eqx.nn.MLP (pointwise)
    transforms: list
    vector_field: Optional[FlowMatchingVectorField]

    F:      jnp.ndarray   # (d_x, d_x)  transition matrix (raw; use F_stable)
    G_chol: jnp.ndarray   # (d_x, d_x)  lower-tri Cholesky of Q = G Gᵀ

    d_x:        int   = eqx.field(static=True)
    d_y:        int   = eqx.field(static=True)
    d_u:        int   = eqx.field(static=True)
    d_out:      int   = eqx.field(static=True)
    seg_len:    int   = eqx.field(static=True)
    max_rho:    float = eqx.field(static=True)
    pointwise:  bool  = eqx.field(static=True)
    flow_type:  str   = eqx.field(static=True)

    def __init__(
        self,
        d_x:          int,
        d_y:          int        = -1,
        d_u:          int        = 0,
        d_enc:        int        = 64,
        d_out:        int        = 96,
        seg_len:      int        = 0,   # 0 = full sequence (no segmentation)
        encoder_type: str        = "transformer",
        local_window: bool       = False,
        local_window_prev_only: bool = False,
        gru_hidden:   int        = 64,
        d_model:      int        = 64,
        n_heads:      int        = 4,
        d_ff:         int        = 256,
        n_layers:     int        = 3,
        flow_type:    str        = "realnvp",
        n_coupling:   int        = 8,
        hidden_size:  int        = 128,
        n_hidden:     int        = 2,
        num_bins:     int        = 8,
        max_rho:      float      = 0.95,
        key:          jr.PRNGKey = jr.PRNGKey(0),
    ):
        if seg_len < 0 or not 0 < max_rho < 1:
            raise ValueError("seg_len must be nonnegative and max_rho must be in (0,1)")
        self.d_x      = d_x
        self.d_y      = d_x if d_y < 0 else d_y
        self.d_u      = d_u
        self.d_out    = d_out
        self.seg_len  = seg_len
        self.max_rho  = max_rho
        self.pointwise = (encoder_type == "pointwise")
        self.flow_type = flow_type.lower()

        k_enc, k_flow, k_F, k_G = jr.split(key, 4)

        if encoder_type == "pointwise":
            # ── Pointwise encoder: cond_t = MLP(y_t, u_t) ────────────────
            # Each step is conditioned ONLY on the local observation y_t and
            # control u_t.  No future information enters cond_t; temporal
            # context is carried entirely by the SSM latent and x_{t-1}.
            self.encoder = eqx.nn.MLP(
                in_size    = self.d_y + max(d_u, 1),
                out_size   = d_out,
                width_size = d_enc,
                depth      = n_hidden,
                key        = k_enc,
            )
        else:
            # ── Full-sequence encoder (transformer / GRU) ─────────────────
            self.encoder = StateConditionEncoder(
                d_y          = self.d_y,
                d_u          = d_u,
                d_x          = d_x,
                d_enc        = d_enc,
                d_out        = d_out,
                key          = k_enc,
                encoder_type = encoder_type,
                local_window = local_window,
                local_window_prev_only = local_window_prev_only,
                gru_hidden   = gru_hidden,
                d_model      = d_model,
                n_heads      = n_heads,
                d_ff         = d_ff,
                n_layers     = n_layers,
            )

        # ── Conditional decoder: z_t ↔ x_t | [x_{t-1}, cond_t] ──────────
        # Normalizing-flow variants use exact change of variables. FM learns
        # an ODE vector field from latent SSM samples z_t to data states x_t.
        if self.flow_type == "fm":
            self.transforms = []
            self.vector_field = FlowMatchingVectorField(
                d_x, d_out + d_x, hidden_size, n_hidden, k_flow
            )
        else:
            self.transforms = build_flow_transforms(
                input_dim   = d_x,
                cond_dim    = d_out + d_x,   # encoder output + previous state
                n_blocks    = n_coupling,
                hidden_size = hidden_size,
                n_hidden    = n_hidden,
                flow_type   = self.flow_type,
                key         = k_flow,
                num_bins    = num_bins,
            )
            self.vector_field = None

        # ── Linear Gaussian SSM ───────────────────────────────────────────
        # F init: ρ=0.8 diagonal — faster decay suited to chaotic systems
        # (0.8^seg_len ≈ 0.33 residual memory per segment, vs 0.77 at ρ=0.95).
        self.F      = 0.80 * jnp.eye(d_x) + 0.05 * jr.normal(k_F, (d_x, d_x))
        # G_chol init: larger noise (1.0*I) to give a wider SSM prior,
        # which helps avoid posterior undercoverage.
        raw_G       = jr.normal(k_G, (d_x, d_x)) * 0.1
        self.G_chol = jnp.tril(raw_G) + 1.0 * jnp.eye(d_x)

    # ------------------------------------------------------------------
    # Encoding helper  (dispatches pointwise vs full-sequence encoder)
    # ------------------------------------------------------------------

    def _encode(
        self,
        y:  jnp.ndarray,   # (T, d_y)
        u:  jnp.ndarray,   # (T, d_u)
        x0: jnp.ndarray,   # (d_x,)
    ) -> jnp.ndarray:      # (T, d_out)
        """
        Returns per-step conditioning vectors cond_{1:T}.

        pointwise  — cond_t = MLP([y_t, u_t]).  Each step sees only its own
                     observation; no future information leaks in.
        sequence   — cond_t = Encoder(y_{1:T}, u_{1:T}, x0)_t.  Full smoother.
        """
        if self.pointwise:
            u_in = u if self.d_u > 0 else jnp.zeros((y.shape[0], 1))
            inp  = jnp.concatenate([y, u_in], axis=-1)   # (T, d_y + d_u)
            return jax.vmap(self.encoder)(inp)            # (T, d_out)
        else:
            return self.encoder(y[None], u[None], x0[None])[0]   # (T, d_out)

    # ------------------------------------------------------------------
    # SSM parameter helpers
    # ------------------------------------------------------------------

    @property
    def F_stable(self) -> jnp.ndarray:
        """F rescaled so spectral radius ≤ max_rho."""
        rho   = jnp.max(jnp.abs(jnp.linalg.eigvals(self.F)))
        scale = jnp.minimum(self.max_rho / jax.lax.stop_gradient(rho), 1.0)
        return self.F * scale

    @staticmethod
    def _to_chol(raw: jnp.ndarray) -> jnp.ndarray:
        L = jnp.tril(raw, k=-1)
        d = jax.nn.softplus(jnp.diag(raw)) + 1e-4
        return L + jnp.diag(d)

    @property
    def G_chol_pd(self) -> jnp.ndarray:
        return self._to_chol(self.G_chol)

    @property
    def Q(self) -> jnp.ndarray:
        L = self.G_chol_pd
        return L @ L.T

    @property
    def P_inf(self) -> jnp.ndarray:
        """Stationary covariance via Kronecker solve: (I - F⊗F) vec(P) = vec(Q)."""
        F, Q = self.F_stable, self.Q
        n = self.d_x
        A = jnp.eye(n * n) - jnp.kron(F, F)
        return jnp.linalg.solve(A, Q.ravel()).reshape(n, n)

    # ------------------------------------------------------------------
    # SSM log-probability  log p(z_{1:T})
    # ------------------------------------------------------------------

    def _ssm_log_prob(self, z: jnp.ndarray) -> jnp.ndarray:
        """
        log N(z_1; 0, P_inf) + Σ_{t=2}^{T} log N(z_t; F z_{t-1}, Q).
        z : (T, d_x)
        """
        d   = self.d_x
        G_L = self.G_chol_pd
        F   = self.F_stable

        # z_1 ~ N(0, P_inf)  — stationary distribution
        L_inf   = jnp.linalg.cholesky(self.P_inf + 1e-6 * jnp.eye(d))
        z1      = z[0]
        a1      = jax.scipy.linalg.solve_triangular(L_inf, z1, lower=True)
        lp_z1   = -0.5 * (jnp.dot(a1, a1) + d * jnp.log(2.0 * jnp.pi)
                          + 2.0 * jnp.sum(jnp.log(jnp.diag(L_inf))))

        z_prev = z[:-1]
        z_curr = z[1:]
        z_pred = jax.vmap(lambda zp: F @ zp)(z_prev)
        resid  = z_curr - z_pred
        alpha  = jax.vmap(
            lambda r: jax.scipy.linalg.solve_triangular(G_L, r, lower=True)
        )(resid)
        log_det  = jnp.sum(jnp.log(jnp.diag(G_L)))
        lp_trans = -0.5 * (
            jnp.sum(alpha ** 2, axis=-1)
            + d * jnp.log(2.0 * jnp.pi)
            + 2.0 * log_det
        )
        return lp_z1 + jnp.sum(lp_trans)

    def _sample_ssm_prior(self, key: jr.PRNGKey, T: int) -> jnp.ndarray:
        """Draw the decoder source: SSM for exact NF, iid Gaussian for FM.

        Autoregressive per-state FM is trained conditional on a true preceding
        state. Its source must stay independent of that condition at inference;
        reusing correlated SSM noise would change this conditional source law.
        """
        if T < 1:
            raise ValueError("Source length must be positive")
        if self.flow_type == "fm":
            return jr.normal(key, (T, self.d_x))
        F = self.F_stable
        G_L = self.G_chol_pd
        L_inf = jnp.linalg.cholesky(self.P_inf + 1e-6 * jnp.eye(self.d_x))
        keys_z = jr.split(key, T)
        z1 = L_inf @ jr.normal(keys_z[0], (self.d_x,))

        def ssm_step(z_p, k_i):
            z_t = F @ z_p + G_L @ jr.normal(k_i, (self.d_x,))
            return z_t, z_t

        _, z_rest = jax.lax.scan(ssm_step, z1, keys_z[1:])
        return jnp.concatenate([z1[None], z_rest], axis=0)

    def _fm_decode_step(
        self,
        z:      jnp.ndarray,   # (d_x,)
        x_prev: jnp.ndarray,   # (d_x,)
        cond:   jnp.ndarray,   # (d_out,)
        steps:  int = 100,
    ) -> jnp.ndarray:
        """Decode one latent state with Euler integration of the FM ODE."""
        c = jnp.concatenate([x_prev, cond])
        dt = 1.0 / steps
        vf = self.vector_field

        def step(x_curr, i):
            t = i * dt
            v = vf(t, x_curr, c)
            return x_curr + v * dt, None

        x1, _ = jax.lax.scan(step, z, jnp.arange(steps))
        return x1

    def _fm_loss_segment(
        self,
        x_seg:    jnp.ndarray,   # (T, d_x)
        cond_seg: jnp.ndarray,   # (T, d_out)
        x_start:  jnp.ndarray,   # (d_x,)
        key:      jr.PRNGKey,
    ) -> jnp.ndarray:
        """Flow-matching MSE for one segment, pairing independent Gaussian sources with conditional target states."""
        T = x_seg.shape[0]
        z0 = self._sample_ssm_prior(key, T)
        x_prev = jnp.concatenate([x_start[None], x_seg[:-1]], axis=0)
        c = jnp.concatenate([x_prev, cond_seg], axis=-1)

        kt = jr.fold_in(key, 1)
        t = jr.uniform(kt, (T,))
        t_b = t[:, None]
        z_t = (1.0 - t_b) * z0 + t_b * x_seg
        v_target = x_seg - z0
        v_pred = jax.vmap(self.vector_field)(t, z_t, c)
        return jnp.mean((v_pred - v_target) ** 2)

    # ------------------------------------------------------------------
    # Internal: encode one segment  (parallel vmap over seg_len steps)
    # ------------------------------------------------------------------

    def _encode_segment(
        self,
        x_seg:    jnp.ndarray,   # (seg, d_x)  true states in segment
        cond_seg: jnp.ndarray,   # (seg, d_out)
        x_start:  jnp.ndarray,   # (d_x,)  boundary state before segment
    ) -> Tuple[jnp.ndarray, jnp.ndarray]:
        """Encode the triangular autoregressive map with true predecessors.

        The diagonal Jacobian blocks are d z_t/d x_t at fixed x_{t-1}; their
        log determinants sum to the full triangular map's log determinant.
        """
        predecessors = jnp.concatenate((x_start[None], x_seg[:-1]), axis=0)
        return jax.vmap(lambda xt, xp, ct: _flow_fwd_single(
            self.transforms, xt, xp, ct
        ))(x_seg, predecessors, cond_seg)

    def _segments(self, length, restart=True):
        if length < 1:
            raise ValueError("A trajectory must contain at least one state")
        width = self.seg_len if restart and self.seg_len > 0 else length
        return [(start, min(start + width, length))
                for start in range(0, length, width)]

    # ------------------------------------------------------------------
    # Single-sequence log p(x_{1:T})
    # ------------------------------------------------------------------

    def log_prob(
        self,
        x:  jnp.ndarray,   # (T, d_x)
        y:  jnp.ndarray,   # (T, d_y)
        u:  jnp.ndarray,   # (T, d_u)
        x0: jnp.ndarray,   # (d_x,)
        restart_segments: bool = True,
    ) -> jnp.ndarray:
        assert self.flow_type != "fm", "log_prob not available for FM; use nll_loss with a key."
        cond = self._encode(y, u, x0)
        total = jnp.asarray(0.0, x.dtype)
        for start, stop in self._segments(x.shape[0], restart_segments):
            predecessor = x0 if start == 0 else x[start - 1]
            z, logdet = self._encode_segment(x[start:stop], cond[start:stop], predecessor)
            total = total + jnp.sum(logdet) + self._ssm_log_prob(z)
        return total

    # ------------------------------------------------------------------
    # Batch NLL loss
    # ------------------------------------------------------------------

    def nll_loss(
        self,
        x:  jnp.ndarray,   # (M, T, d_x)
        y:  jnp.ndarray,   # (M, T, d_y)
        u:  jnp.ndarray,   # (M, T, d_u)
        x0: jnp.ndarray,   # (M, d_x)
        key: Optional[jr.PRNGKey] = None,
    ) -> jnp.ndarray:
        """Batch loss. NF: NLL. FM: flow-matching MSE."""
        if self.flow_type == "fm":
            assert key is not None, "FM loss requires a PRNG key."
            return self.fm_loss(x, y, u, x0, key)
        T         = x.shape[1]
        log_probs = jax.vmap(self.log_prob)(x, y, u, x0)
        return -jnp.mean(log_probs) / T

    def fm_loss(
        self,
        x:  jnp.ndarray,   # (M, T, d_x)
        y:  jnp.ndarray,   # (M, T, d_y)
        u:  jnp.ndarray,   # (M, T, d_u)
        x0: jnp.ndarray,   # (M, d_x)
        key: jr.PRNGKey,
    ) -> jnp.ndarray:
        """Batch flow-matching loss for the latent SSM decoder."""
        M, T, _ = x.shape
        cond = jax.vmap(self._encode)(y, u, x0)
        total = jnp.asarray(0.0, x.dtype)
        for index, (start, stop) in enumerate(self._segments(T)):
            predecessors = x0 if start == 0 else x[:, start - 1]
            keys = jr.split(jr.fold_in(key, index), M)
            losses = jax.vmap(self._fm_loss_segment)(
                x[:, start:stop], cond[:, start:stop], predecessors, keys)
            total = total + (stop - start) * jnp.mean(losses)
        return total / T

    # ------------------------------------------------------------------
    # Entropy regularizer
    # ------------------------------------------------------------------

    def _entropy_reg_single(
        self,
        y:         jnp.ndarray,   # (T, d_y)
        u:         jnp.ndarray,   # (T, d_u)
        x0:        jnp.ndarray,   # (d_x,)
        key:       jr.PRNGKey,
        n_samples: int = 4,
    ) -> jnp.ndarray:
        """
        Estimate  -H[q(x_{1:T} | y_{1:T})]  for one sequence via Monte Carlo.

        Decomposition:
            H[q] = H[p_SSM(z)] + E_{z ~ p_SSM}[ Σ_t log|J⁻¹_t(z_t; cond_t, x̂_{t-1})| ]

        The second term is estimated by sampling z from the SSM prior, running
        the autoregressive inverse flow, and summing the log|J⁻¹| at each step.
        The first term (H[p_SSM]) depends only on the SSM parameters and provides
        its own gradient signal; we include it analytically below.

        Returns a scalar to be added to NLL with weight +lambda_ent.
        Minimising it (= maximising H[q]) widens the posterior.
        """
        if n_samples < 1:
            raise ValueError("n_samples must be positive")
        if self.flow_type == "fm":
            raise ValueError("Exact entropy is available for normalizing-flow decoders only")
        T, d = y.shape[0], self.d_x
        cond = self._encode(y, u, x0)
        segments = self._segments(T)
        L_inf = jnp.linalg.cholesky(self.P_inf + 1e-6 * jnp.eye(d))
        log_det_P = 2 * jnp.log(jnp.diag(L_inf)).sum()
        log_det_Q = 2 * jnp.log(jnp.diag(self.G_chol_pd)).sum()
        count = len(segments)
        h_prior = .5 * (count * log_det_P + (T - count) * log_det_Q
                        + T * d * (1 + jnp.log(2 * jnp.pi)))

        def one_sample(draw_key):
            boundary = x0
            logdet = jnp.asarray(0.0, x0.dtype)
            for index, (start, stop) in enumerate(segments):
                z = self._sample_ssm_prior(jr.fold_in(draw_key, index), stop-start)
                def decode(previous, inputs):
                    state, ld = _flow_inv_single(self.transforms, inputs[0], previous, inputs[1])
                    return state, ld
                boundary, ld = jax.lax.scan(decode, boundary, (z, cond[start:stop]))
                logdet = logdet + jnp.sum(ld)
            return logdet
        return -(h_prior + jnp.mean(jax.vmap(one_sample)(jr.split(key, n_samples))))

    def entropy_reg_loss(
        self,
        y:         jnp.ndarray,   # (M, T, d_y)
        u:         jnp.ndarray,   # (M, T, d_u)
        x0:        jnp.ndarray,   # (M, d_x)
        key:       jr.PRNGKey,
        n_samples: int = 4,
    ) -> jnp.ndarray:
        """
        Batch entropy regularizer: mean_M [ -H[q(x|y_m)] ] / T.

        Add to nll_loss with weight lambda_ent:
            loss = model.nll_loss(x, y, u, x0) \
                 + lambda_ent * model.entropy_reg_loss(y, u, x0, key)
        """
        T    = y.shape[1]
        keys = jr.split(key, y.shape[0])
        neg_H = jax.vmap(
            lambda yi, ui, x0i, ki: self._entropy_reg_single(yi, ui, x0i, ki, n_samples)
        )(y, u, x0, keys)
        return jnp.mean(neg_H) / T

    # ------------------------------------------------------------------
    # Encode latents  z_t = flow(x_t; [cond_t, x_{t-1}])
    # ------------------------------------------------------------------

    def encode_latents(
        self,
        x:  jnp.ndarray,
        y:  jnp.ndarray,
        u:  jnp.ndarray,
        x0: jnp.ndarray,
    ) -> Tuple[jnp.ndarray, jnp.ndarray]:
        """Returns (z, cond), both (T, *)."""
        if self.flow_type == "fm":
            raise ValueError("encode_latents requires a normalizing-flow decoder")
        cond = self._encode(y, u, x0)
        chunks = []
        for start, stop in self._segments(x.shape[0]):
            predecessor = x0 if start == 0 else x[start - 1]
            z, _ = self._encode_segment(x[start:stop], cond[start:stop], predecessor)
            chunks.append(z)
        return jnp.concatenate(chunks), cond

    # ------------------------------------------------------------------
    # Reconstruction  (encode then decode with true x_prev — ~identity)
    # ------------------------------------------------------------------

    def reconstruct(
        self,
        x:  jnp.ndarray,
        y:  jnp.ndarray,
        u:  jnp.ndarray,
        x0: jnp.ndarray,
    ) -> jnp.ndarray:
        """x_t → z_t → x̂_t using true x_prev.  Should be ~identity."""
        assert self.flow_type != "fm", "reconstruct is only exact for normalizing-flow variants."
        cond = self._encode(y, u, x0)
        previous = jnp.concatenate((x0[None], x[:-1]), axis=0)
        z, _ = jax.vmap(lambda xt, xp, ct: _flow_fwd_single(
            self.transforms, xt, xp, ct))(x, previous, cond)
        restored, _ = jax.vmap(lambda zt, xp, ct: _flow_inv_single(
            self.transforms, zt, xp, ct))(z, previous, cond)
        return restored

    # ------------------------------------------------------------------
    # Posterior sampling
    # ------------------------------------------------------------------

    def sample_posterior(
        self,
        y:          jnp.ndarray,
        u:          jnp.ndarray,
        x0:         jnp.ndarray,
        key:        jr.PRNGKey,
        n_samples:  int           = 1,
        seg_starts: jnp.ndarray   = None,
        x:          jnp.ndarray   = None,
        restart_segments: bool    = True,
    ) -> jnp.ndarray:
        """
        Draw posterior samples x_{1:T} | y_{1:T}.  Returns (n_samples, T, d_x).

        Segmented evaluation (seg_len > 0):
          - Each segment samples z_1 ~ N(0, P_inf) and runs the SSM forward.
          - Decoding is autoregressive within a segment.
          - The first segment starts from x0; later segments start from the
            generated final state of the previous segment.

        Full sequence (seg_len <= 0 or restart_segments=False):
          - One SSM trajectory z_{1:T}, sequential autoregressive decode.
        """
        if x is not None or seg_starts is not None:
            raise ValueError("Sampling accepts observations and x0, not ground-truth segment starts")
        T = y.shape[0]
        cond = self._encode(y, u, x0)
        segments = self._segments(T, restart_segments)
        def one_sample(draw_key):
            boundary = x0
            chunks = []
            for index, (start, stop) in enumerate(segments):
                z = self._sample_ssm_prior(jr.fold_in(draw_key, index), stop-start)
                def decode(previous, inputs):
                    zt, ct = inputs
                    if self.flow_type == "fm":
                        state = self._fm_decode_step(zt, previous, ct)
                    else:
                        state, _ = _flow_inv_single(self.transforms, zt, previous, ct)
                    return state, state
                boundary, chunk = jax.lax.scan(decode, boundary, (z, cond[start:stop]))
                chunks.append(chunk)
            return jnp.concatenate(chunks)
        return jax.vmap(one_sample)(jr.split(key, n_samples))


