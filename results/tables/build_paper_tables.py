"""Write the manuscript tables that depend on the final runs: tables/main_results.tex (mean +- SD over 3 seeds, with the
reference filters) and tables/latency.tex (median ms per test window at equal sample/particle count, seed 0, from the
equal-n sweep). Numbers come from tables/summary.json, filters/*/summary.json and analyses/equal_n/rows.jsonl."""
import json, statistics as st
from pathlib import Path
P = Path(__file__).resolve().parents[1]; T = P.parent / "paper" / "tables"  # <archive>/results and <archive>/paper/tables
rows = json.loads((P / "tables/summary.json").read_text())["rows"]
DS = [("pendulum", "Pendulum", 128), ("lorenz96", r"Lorenz--96", 200), ("aloha", "ALOHA", 200), ("reassemble", "REASSEMBLE", 500)]
METHODS = [("normflowsde", r"\method"), ("nf_dpf", "NF-DPF"), ("nsf", "NSF"), ("flowsde", "FlowSDE")]
KEYS = ("rmse", "crps", "coverage_90", "mean_interval_width")
def pm(r, k, d): return f"{r[k]:.{d}f} $\\pm$ {r[k+'_sd']:.{d}f}"
def best(cands, k):
    return min(cands, key=(lambda m: abs(rows[m][k] - 0.9)) if k == "coverage_90" else (lambda m: rows[m][k]))
PARTICLES = {"pendulum": 500, "lorenz96": 1000, "aloha": 200, "reassemble": 500}  # protocol particle counts of the PF rows
eq = [json.loads(l) for l in open(P / "analyses/equal_n/rows.jsonl")]
lat = {(r["dataset"], r["method"], r["n"]): r["latency"]["ms_per_window_median"] for r in eq if r["seed"] == 0 and r.get("latency")}
ref_file = P / "analyses/latency_filters/latency.json"  # reference filters, same protocol, L40S
reflat = {(r["dataset"], r["filter"]): r["ms_per_window_median"] for r in json.loads(ref_file.read_text())["rows"]} if ref_file.exists() else {}
def row_latency(ds, m, M): return lat[(ds, m, M if m == "normflowsde" else PARTICLES[ds])]
hdr = "% Generated by results/tables/build_paper_tables.py; do not edit numbers."
out = [hdr, r"\begin{tabular}{llccccc}", r"\toprule", r"Dataset & Method & RMSE $\downarrow$ & CRPS $\downarrow$ & Cov.\ 90\% & Width & Latency (ms) $\downarrow$ \\", r"\midrule"]
def filt(ds, f):
    s = json.loads((P / f"filters/{ds}/summary.json").read_text()); rs = [r["test"] for r in s["rows"] if r["filter"] == f and r["misspecification"] == 0]
    return {**{k: st.mean(r[k] for r in rs) for k in KEYS}, **{k + "_sd": st.stdev(r[k] for r in rs) for k in KEYS}}
REFS = {"pendulum": [("ekf", "EKF / UKF"), ("pf", "bootstrap PF")], "lorenz96": [("ekf", "EKF / UKF"), ("pf", "bootstrap PF")]}
for di, (ds, name, M) in enumerate(DS):
    cands = [f"{ds}/{m}" for m, _ in METHODS]; b = {k: best(cands, k) for k in KEYS}
    lats = {m: row_latency(ds, m, M) for m, _ in METHODS}; fastest = min(lats, key=lats.get)
    for i, (m, label) in enumerate(METHODS):
        key = f"{ds}/{m}"; r = rows[key]
        cells = [pm(r, k, 3 if k == "coverage_90" else 4) for k in KEYS]
        cells = [(r"\textbf{" + c + "}") if b[k] == key and k != "mean_interval_width" else c for c, k in zip(cells, KEYS)]
        cells.append((r"\textbf{" if m == fastest else "") + f"{lats[m]:.1f}" + ("}" if m == fastest else ""))
        out.append(f"{name if i == 0 else ''} & {label} & " + " & ".join(cells) + r" \\")
    for f, label in REFS.get(ds, []):
        r = filt(ds, f)
        lat_ref = " / ".join(f"{reflat[(ds, g)]:.1f}" for g in (("ekf", "ukf") if f == "ekf" else (f,))) if (ds, f) in reflat else "--"
        out.append(f" & {label} & " + " & ".join(pm(r, k, 3 if k == 'coverage_90' else 4) for k in KEYS) + f" & {lat_ref} " + r"\\")
    out.append(r"\midrule" if di < len(DS) - 1 else r"\bottomrule")
out += [r"\end{tabular}", ""]
(T / "main_results.tex").write_text("\n".join(out))
# latency at equal count M (seed 0), separate table (no longer input by the manuscript)
out = [hdr, r"\begin{tabular}{lccccc}", r"\toprule", r"Dataset & $M$ & \method & NF-DPF & NSF & FlowSDE \\", r"\midrule"]
for ds, name, M in DS:
    vals = [lat[(ds, m, M)] for m, _ in METHODS]; b = min(range(4), key=lambda i: vals[i])
    out.append(f"{name} & {M} & " + " & ".join((r"\textbf{" if i == b else "") + f"{v:.1f}" + ("}" if i == b else "") for i, v in enumerate(vals)) + r" \\")
out += [r"\bottomrule", r"\end{tabular}", ""]
(T / "latency.tex").write_text("\n".join(out))
# speed-up range for the text
sp = [min(lat[(ds, m, M)] for m, _ in METHODS[1:]) / lat[(ds, "normflowsde", M)] for ds, _, M in DS]
sp2 = [max(lat[(ds, m, M)] for m, _ in METHODS[1:]) / lat[(ds, "normflowsde", M)] for ds, _, M in DS]
sp3 = [min(row_latency(ds, m, M) for m, _ in METHODS[1:]) / row_latency(ds, "normflowsde", M) for ds, _, M in DS]
sp4 = [max(row_latency(ds, m, M) for m, _ in METHODS[1:]) / row_latency(ds, "normflowsde", M) for ds, _, M in DS]
print("main-table configuration: speed-up vs fastest PF", [round(x, 2) for x in sp3], "vs slowest", [round(x, 2) for x in sp4])
print("speed-up vs fastest PF per dataset:", [round(x, 2) for x in sp], "vs slowest:", [round(x, 2) for x in sp2])
print("wrote", T / "main_results.tex", T / "latency.tex")
