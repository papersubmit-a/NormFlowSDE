"""Benchmark tables of the manuscript for the shared-trunk campaign (2026-11-16).

Writes paper/tables/benchmark_sim.tex (pendulum, Lorenz-96, with the model-based reference filters) and
paper/tables/benchmark_robot.tex (ALOHA, REASSEMBLE): mean +- sample SD over seeds 0-2 of the test RMSE, CRPS, 90 %
coverage and mean interval width, and the seed-0 latency on one L40S. Nothing is typed in:
  runs      results/shared_trunk_20261114/BENCHMARK_SUMMARY.sources.json (the run directory of every cell, written by
            results/provenance/shared_trunk_20261114/build_benchmark_summary.py) -> <run>/summary.json["test"]
  latency   results/analyses/equal_n_shared_trunk_20261117/latency_l40s/rows.jsonl (all eight methods, job 36123),
            at the protocol count of each method, taken from the n of
            results/analyses/latency_gpu_20261116_shared_trunk/rows.jsonl (job 35895)
  ref.      results/filters/<dataset>/summary.json and results/analyses/latency_filters/latency.json, as
            build_paper_tables.py
Also writes results/tables/shared_trunk_summary.json with every number of the two tables.

  python results/tables/build_shared_trunk_tables.py
"""
import json
import statistics as st
from pathlib import Path

P = Path(__file__).resolve().parents[1]
ROOT = P.parent
T = ROOT / "paper" / "tables"
KEYS = ("rmse", "crps", "coverage_90", "mean_interval_width")
GROUPS = [("direct", [("normflowsde", "NormFlowSDE"), ("latent_nsf", "Latent NSF"), ("latent_sde", "Latent SDE"),
                      ("sigker_sde", "SigKer SDE")]),
          ("PF", [("nf_dpf", "NF-DPF"), ("nsf", "NSF-PF"), ("flowsde", "FlowSDE-PF"), ("normflowsde_pf", "NormFlowSDE-PF")])]
TABLES = {"benchmark_sim": [("pendulum", "Pendulum"), ("lorenz96", "Lorenz--96")],
          "benchmark_robot": [("aloha", "ALOHA"), ("reassemble", "REASSEMBLE")]}
REFS = [("ekf", "EKF / UKF"), ("pf", "bootstrap PF")]

cells = json.loads((P / "shared_trunk_20261114/BENCHMARK_SUMMARY.sources.json").read_text())["cells"]
# The protocol count of each (dataset, method) is the n of job 35895, which timed exactly those counts.
protocol_n = {(r["dataset"], r["method"]): r["n"] for r in map(json.loads, (
    P / "analyses/latency_gpu_20261116_shared_trunk/rows.jsonl").read_text().splitlines()) if r["seed"] == 0}
latency = {}
for line in (P / "analyses/equal_n_shared_trunk_20261117/latency_l40s/rows.jsonl").read_text().splitlines():
    row = json.loads(line)
    if row["seed"] == 0 and protocol_n.get((row["dataset"], row["method"])) == row["n"]:
        latency[row["dataset"], row["method"]] = row["latency"]["ms_per_window_median"]
assert set(latency) == set(protocol_n), set(protocol_n) - set(latency)
reference_latency = {(r["dataset"], r["filter"]): r["ms_per_window_median"]
                     for r in json.loads((P / "analyses/latency_filters/latency.json").read_text())["rows"]}


def stats(values):
    return {**{k: st.mean(v[k] for v in values) for k in KEYS}, **{k + "_sd": st.stdev(v[k] for v in values) for k in KEYS}}


def learned(dataset, method):
    runs = cells[f"{method}/{dataset}"]["runs"]
    return stats([json.loads((ROOT / run / "summary.json").read_text())["test"] for run in runs]) | dict(runs=runs)


def reference(dataset, name):
    summary = json.loads((P / f"filters/{dataset}/summary.json").read_text())
    return stats([r["test"] for r in summary["rows"] if r["filter"] == name and r["misspecification"] == 0])


def pm(row, key):
    digits = 3 if key == "coverage_90" else 4
    return f"{row[key]:.{digits}f} $\\pm$ {row[key + '_sd']:.{digits}f}"


summary = {}
for name, datasets in TABLES.items():
    out = ["% Generated by results/tables/build_shared_trunk_tables.py; do not edit numbers.",
           r"\begin{tabular}{lllccccc}", r"\toprule",
           r"Dataset & Route & Method & RMSE $\downarrow$ & CRPS $\downarrow$ & Cov.\ 90\% & Width & Latency (ms) $\downarrow$ \\",
           r"\midrule"]
    for index, (dataset, title) in enumerate(datasets):
        rows = {method: learned(dataset, method) for _, group in GROUPS for method, _ in group}
        best = {key: min(rows, key=(lambda m: abs(rows[m][key] - 0.9)) if key == "coverage_90" else (lambda m: rows[m][key]))
                for key in KEYS[:3]}
        fastest = min(rows, key=lambda m: latency[dataset, m])
        first = True
        for route, group in GROUPS:
            for position, (method, label) in enumerate(group):
                row = rows[method]
                entries = [(r"\textbf{" + pm(row, key) + "}") if best.get(key) == method else pm(row, key) for key in KEYS]
                ms = f"{latency[dataset, method]:.1f}"
                entries.append(r"\textbf{" + ms + "}" if method == fastest else ms)
                out.append(f"{title if first else ''} & {route if position == 0 else ''} & {label} & " + " & ".join(entries) + r" \\")
                first = False
                summary[f"{dataset}/{method}"] = row | dict(latency_ms=latency[dataset, method])
            out.append(r"\cmidrule(l){2-8}")
        if name == "benchmark_sim":
            for position, (ref, label) in enumerate(REFS):
                row = reference(dataset, ref)
                ms = " / ".join(f"{reference_latency[dataset, g]:.1f}" for g in (("ekf", "ukf") if ref == "ekf" else (ref,)))
                out.append(f" & {'ref.' if position == 0 else ''} & {label} & " + " & ".join(pm(row, key) for key in KEYS) + f" & {ms} " + r"\\")
                summary[f"{dataset}/reference_{ref}"] = row
        else:
            out.pop()
        out.append(r"\midrule" if index < len(datasets) - 1 else r"\bottomrule")
    out += [r"\end{tabular}", ""]
    (T / f"{name}.tex").write_text("\n".join(out))
    print("wrote", T / f"{name}.tex")
(P / "tables/shared_trunk_summary.json").write_text(json.dumps(summary, indent=1) + "\n")
for key, row in summary.items():
    print(f"{key:32s} " + "  ".join(f"{k} {row[k]:.4f}+-{row[k + '_sd']:.4f}" for k in KEYS)
          + (f"  latency {row['latency_ms']:.1f}" if "latency_ms" in row else ""))
