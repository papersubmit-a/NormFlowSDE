"""Observation-noise comparison per dataset: Gaussian (2026-10-19 campaign) vs GMM (final table), with the
model-based reference filters on the two simulated systems. Writes table.md, summary.json, noise_<dataset>.tex
and copies the .tex files to paper/tables/."""
import json, os, statistics as st, shutil
from pathlib import Path
P = Path(__file__).resolve().parents[2]; A = Path("/home/anon/bayesinf_jax/results/results_arxiv")  # A: superseded Gaussian-noise runs, NOT part of this archive
OUT = Path(__file__).resolve().parent; PAPER = P.parent / "paper" / "tables"
KEYS = ("rmse", "crps", "coverage_90", "mean_interval_width")
DS = [("pendulum", "Pendulum"), ("lorenz96", "Lorenz--96"), ("aloha", "ALOHA"), ("reassemble", "REASSEMBLE")]
METHODS = [("normflowsde", "NormFlowSDE"), ("nf_dpf", "NF-DPF"), ("nsf", "NSF"), ("flowsde", "FlowSDE")]
FILTERS = [("ekf", "EKF"), ("ukf", "UKF"), ("pf", "Bootstrap PF")]

def agg(tests, runs):
    return {**{k: st.mean(t[k] for t in tests) for k in KEYS}, **{k + "_sd": st.stdev(t[k] for t in tests) for k in KEYS}, "runs": runs}
def load_metrics(p):
    m = json.loads(Path(p).read_text()); m = m.get("metrics", m); return {k: m[k] for k in KEYS}

rows = {}  # (dataset, noise, method) -> agg
final = json.loads((P / "tables/summary.json").read_text())["rows"]
gauss = A / "results_paper_filter_campaign_20261020"
for ds, _ in DS:
    for m, _ in METHODS:
        rows[(ds, "gmm", m)] = final[f"{ds}/{m}"]
        if ds != "lorenz96":  # the 2026-10-19 campaign used Gaussian observation noise on these three datasets
            runs = [str(gauss / ds / m / f"seed{s}") for s in range(3)]
            rows[(ds, "gaussian", m)] = agg([load_metrics(r + "/metrics.json") for r in runs], runs)
def filters(summary, noise, ds):
    s = json.loads(Path(summary).read_text())
    for f, _ in FILTERS + [("pf_gauss", "")]:
        rs = [r for r in s["rows"] if r["filter"] == f and r["misspecification"] == 0]
        if rs: rows[(ds, noise, f)] = agg([{k: r["test"][k] for k in KEYS} for r in rs], [str(Path(summary).parent / f / "s0" / f"seed{r['seed']}") for r in rs])
filters(A / "model_based_baselines_20261019/pendulum/summary.json", "gaussian", "pendulum")
filters(P / "filters/pendulum/summary.json", "gmm", "pendulum")
filters(P / "filters/lorenz96/summary.json", "gmm", "lorenz96")

NOISE = [("gaussian", "Gaussian"), ("gmm", "GMM")]
def fmt(r, k):
    return f"{r[k]:.3f} ± {r[k+'_sd']:.3f}" if k == "coverage_90" else f"{r[k]:.4f} ± {r[k+'_sd']:.4f}"
def best(cands, key):
    if key == "coverage_90": return min(cands, key=lambda m: abs(rows[m][key] - 0.9))
    return min(cands, key=lambda m: rows[m][key])
md = ["# Observation-noise comparison per dataset (test split, mean ± SD over 3 seeds)", "",
      "Gaussian rows: all-filtering campaign of 2026-10-19 (results_arxiv/results_paper_filter_campaign_20261020; Gaussian observation noise, std 0.1 normalized), "
      "campaign recipe with per-seed validation selection. GMM rows: the final benchmark table (tables/table.md; mixture noise, weights 0.7/0.3, see datasets/*/cache.json). "
      "Lorenz--96 is observed through the mixture in both campaigns, so it has no Gaussian rows. Reference filters use the true dynamics and measurement model "
      "(EKF/UKF use the moment-matched Gaussian likelihood on GMM data; the bootstrap PF uses the exact likelihood; noise level validation-selected, 3 seeds); "
      "they exist only for the simulated systems. NormFlowSDE's GMM rows for pendulum (stage-1 rollout weight 30), Lorenz--96 (stage-1 lr 2e-3, stage-2 lr 3e-5, CRPS-selected) "
      "and REASSEMBLE (energy spread factor 0.52) use the coverage-round settings, whereas the Gaussian rows use the campaign recipe; the three baselines use the same recipe and grids in both campaigns. "
      "Bold: best RMSE / CRPS / width and coverage closest to 0.90 among the learned methods within a noise block.", ""]
tex_note = "% Generated by results/analyses/noise_recovery/build.py; do not edit numbers."
summary = {}
for ds, dname in DS:
    md += [f"## {dname}", "", "| Noise | Method | RMSE ↓ | CRPS ↓ | Cov. 90% (target 0.90) | Width |", "|---|---|---|---|---|---|"]
    tex = [tex_note, r"\begin{tabular}{llrrrr}", r"\toprule", r"Noise & Method & RMSE $\downarrow$ & CRPS $\downarrow$ & Cov.\ 90\% & Width \\", r"\midrule"]
    for noise, nname in NOISE:
        learned = [(ds, noise, m) for m, _ in METHODS if (ds, noise, m) in rows]
        if not learned: continue
        bests = {k: best(learned, k) for k in KEYS}
        for m, mname in METHODS + FILTERS:
            key = (ds, noise, m)
            if key not in rows: continue
            r = rows[key]; cells = [fmt(r, k) for k in KEYS]
            if m in dict(METHODS):
                cells = [f"**{c}**" if bests[k] == key else c for c, k in zip(cells, KEYS)]
            label = mname if m in dict(METHODS) else f"{mname} (reference)"
            md.append(f"| {nname} | {label} | " + " | ".join(cells) + " |")
            tcells = [c.replace("**", "").replace(" ± ", r" $\pm$ ") for c in cells]
            tcells = [(r"\textbf{" + c + "}") if c0.startswith("**") else c for c, c0 in zip(tcells, cells)]
            tex.append(f"{nname} & {label} & " + " & ".join(tcells) + r" \\")
            summary[f"{ds}/{noise}/{m}"] = r
        tex.append(r"\midrule")
    tex[-1] = r"\bottomrule"; tex += [r"\end{tabular}", ""]
    (OUT / f"noise_{ds}.tex").write_text("\n".join(tex)); shutil.copy(OUT / f"noise_{ds}.tex", PAPER / f"noise_{ds}.tex")
    md.append("")
(OUT / "table.md").write_text("\n".join(md) + "\n")
(OUT / "summary.json").write_text(json.dumps(dict(note=md[2], rows=summary), indent=1) + "\n")
print("\n".join(md))
