"""Wrap the paper's Figure 1 (paper/figures/NormFlowSDE_figure.svg) as interactive/overview/figure-svg.js.

The interactive overview page animates this exact drawing. The SVG is embedded as a JS string (not fetched) so that the
page also works from file://, where browsers block fetch(). Run after every change to the paper figure.
Usage: python scripts/sync_overview_figure.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
src = ROOT / 'paper' / 'figures' / 'NormFlowSDE_figure.svg'
dst = ROOT / 'interactive' / 'overview' / 'figure-svg.js'
svg = src.read_text(encoding='utf-8').strip()
assert svg.startswith('<svg') and '</script' not in svg.lower()
dst.parent.mkdir(parents=True, exist_ok=True)
dst.write_text('/* Generated by scripts/sync_overview_figure.py from the paper figure; do not edit. */\n'
               'window.OVERVIEW_SVG = ' + json.dumps(svg) + ';\n', encoding='utf-8')
print(f'{dst.relative_to(ROOT)}: {dst.stat().st_size / 1e3:.0f} kB')
