"""Wrap the robot-view bundle (results/robot_view/<ds>.npz from scripts/export_robot_view.py) as JS data files.

interactive/robot-view/data/<ds>.js sets window.ROBOT_VIEW_DATA[<ds>] = {meta, arrays}; arrays are little-endian base64
with dtype and shape. Reference, measurements, mean and quantiles stay float32 (the page shows them exactly); the ghost
draws are float16. A script file (not fetch) keeps the page working from file://; the page loads it lazily.

Usage: python scripts/make_robot_view_data.py
"""
import base64
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'results' / 'robot_view'
OUT = ROOT / 'interactive' / 'robot-view' / 'data'

JOINTS = {
    'aloha': ([f'{s} {j}' for s in ('left', 'right') for j in
               ('waist', 'shoulder', 'elbow', 'forearm roll', 'wrist angle', 'wrist rotate', 'gripper')],
              ['rad'] * 6 + ['normalized'] + ['rad'] * 6 + ['normalized']),
    'reassemble': ([f'joint {i}' for i in range(1, 8)], ['rad'] * 7),
}
LABEL = {'aloha': 'ALOHA insertion (simulation)', 'reassemble': 'REASSEMBLE (real robot)'}
FIELDS = {'truth': '<f4', 'obs': '<f4', 'mean': '<f4', 'q05': '<f4', 'q50': '<f4', 'q95': '<f4', 'x0': '<f4',
          'draws': '<f2', 'rmse': '<f4', 'window': '<i4'}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for ds in ('aloha', 'reassemble'):
        z = np.load(SRC / f'{ds}.npz')
        info = json.loads((SRC / f'{ds}.json').read_text())
        arrays = {}
        for k, dt in FIELDS.items():
            a = np.ascontiguousarray(z[k].astype(dt))
            arrays[k] = {'dtype': dt[1:], 'shape': list(a.shape), 'b64': base64.b64encode(a.tobytes()).decode('ascii')}
        names, units = JOINTS[ds]
        meta = {k: info[k] for k in ('dataset', 'seed', 'window_rule', 'labels', 'windows', 'rmse', 'mean_rmse',
                                     'n_windows', 'draws_total', 'draws_exported', 'T', 'D', 'dt')}
        meta.update(label=LABEL[ds], joints=names, units=units)
        # exact values for tests/robot-view.test.js: the page's decoder must reproduce them bit for bit
        meta['check'] = {'truth[0,0]': [float(v) for v in z['truth'][0, 0].astype('<f4')],
                         'q50[3,10]': [float(v) for v in z['q50'][3, 10].astype('<f4')],
                         'q95[10,-1]': [float(v) for v in z['q95'][10, -1].astype('<f4')],
                         'draws[1,2,5]': [float(v) for v in z['draws'][1, 2, 5].astype('<f2')]}
        js = OUT / f'{ds}.js'
        js.write_text('/* Generated by scripts/make_robot_view_data.py from the frozen NormFlowSDE runs (seed 0). */\n'
                      f'(window.ROBOT_VIEW_DATA = window.ROBOT_VIEW_DATA || {{}})[{json.dumps(ds)}] = '
                      + json.dumps({'meta': meta, 'arrays': arrays}, separators=(',', ':')) + ';\n', encoding='utf-8')
        print(f'{js.relative_to(ROOT)}: {js.stat().st_size / 1e6:.2f} MB, windows {meta["windows"]}')


if __name__ == '__main__':
    main()
