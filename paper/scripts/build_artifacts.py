#!/usr/bin/env python3
"""Build manuscript tables/figures from frozen evidence; --refresh reads the repo.

No training is performed. Source hashes refer to the original CSV files.
Run from any working directory.
"""
import argparse
import csv
import hashlib
import io
import json
import os
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
ROOT = PAPER.parents[1]
os.environ.setdefault('MPLCONFIGDIR', '/tmp/normflowsde-matplotlib')
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from draw_model_overview import draw_model_overview

LORENZ_METHODS = [('particle_filter_gmm', 'GMM particle filter'),
                 ('normalizing_flow_sde_realnvp', 'NormFlowSDE'),
                 ('conditional_stochastic_interpolant', 'Stochastic interpolant')]
COLORS = {'particle_filter_gmm': '#6B5A9B',
          'normalizing_flow_sde_realnvp': '#007F86',
          'conditional_stochastic_interpolant': '#CB6A31'}
CSV_NAMES = ['state_estimation_lorenz96_comparison.csv',
             'reassemble_three_model_state_estimation.csv',
             'aloha_sim_insertion_all_methods.csv']


def freeze():
    manifest = []
    for name in CSV_NAMES:
        source = Path('evaluation') / name
        raw = (ROOT / source).read_bytes()
        (PAPER / 'evidence' / name).write_bytes(raw)
        manifest.append(dict(path=str(source), sha256=hashlib.sha256(raw).hexdigest()))
    (PAPER / 'evidence/source_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')


def table(filename, spec, header, rows):
    out = ['% Generated by scripts/build_artifacts.py; do not edit numbers.',
           r'\begin{tabular}{' + spec + '}', r'\toprule',
           ' & '.join(header) + r' \\', r'\midrule']
    out.extend(' & '.join(row) + r' \\' for row in rows)
    out.extend([r'\bottomrule', r'\end{tabular}', ''])
    (PAPER / 'tables' / filename).write_text('\n'.join(out))


def build():
    lorenz = list(csv.DictReader(io.StringIO((PAPER / 'evidence/state_estimation_lorenz96_comparison.csv').read_text())))
    records = {}
    for key, _ in LORENZ_METHODS:
        matches = [row for row in lorenz if row['method'] == key and row['noise_type'] == 'gmm3']
        if len(matches) != 1:
            raise ValueError(f'Expected exactly one GMM3 record for {key}, found {len(matches)}')
        records[key] = matches[0]
    rows = []
    for key, name in LORENZ_METHODS:
        row = records[key]
        rows.append([name, row['eval_trajectories'], row['metric_particles'],
                     f"{float(row['rmse_all']):.4f}", f"{float(row['rmse_obs']):.4f}",
                     f"{float(row['rmse_unobs']):.4f}", f"{100*float(row['coverage_90']):.2f}",
                     f"{float(row['mciw_all']):.4f}"])
    table('lorenz96.tex', 'lrrrrrrr',
          ['Estimator', 'N', 'M', r'\shortstack{RMSE\\all}',
           r'\shortstack{RMSE\\observed}', r'\shortstack{RMSE\\unobserved}',
           r'Cov.\ (\%)', 'Width'], rows)
    reassemble = list(csv.DictReader(io.StringIO((PAPER / 'evidence/reassemble_three_model_state_estimation.csv').read_text())))
    labels = ['NormFlowSDE (calibrated)', 'FlowSDE + Gaussian smoother', 'NSF + Gaussian smoother']
    table('reassemble.tex', 'lrrr', ['Estimator', 'RMSE', 'MAE', r'90\% cov.\ (\%)'],
          [[label, f"{float(row['rmse']):.5f}", f"{float(row['mae']):.5f}",
            f"{100*float(row['coverage_90']):.2f}"] for label, row in zip(labels, reassemble)])
    aloha = list(csv.DictReader(io.StringIO((PAPER / 'evidence/aloha_sim_insertion_all_methods.csv').read_text())))
    selected = {'extended_kalman_filter': 'EKF', 'unscented_kalman_filter': 'UKF',
                'bootstrap_particle_filter': 'Bootstrap PF', 'realnvp_flow_sde': 'NormFlowSDE smoother',
                'nsf_particle_filter': 'NSF PF', 'fm_flowsde_particle_filter': 'FlowSDE PF'}
    cases = {'dataset_noisy': 'Noisy demonstration', 'mujoco_random': 'MuJoCo random',
             'pseudo_process_uncertainty': 'Pseudo-process'}
    ar = []
    for row in aloha:
        if row['method'] in selected:
            ar.append([cases[row['dataset']], selected[row['method']],
                       f"{float(row['rmse']):.4f}", f"{float(row['mae']):.4f}",
                       f"{100*float(row['coverage_90']):.2f}"])
    table('aloha.tex', 'llrrr', ['Case', 'Estimator', 'RMSE', 'MAE', r'90\% cov.\ (\%)'], ar)
    plt.rcParams.update({'font.family': 'DejaVu Sans', 'font.size': 9,
                         'axes.spines.top': False, 'axes.spines.right': False,
                         'pdf.fonttype': 42})
    fig, axes = plt.subplots(1, 2, figsize=(10.5, 3.1), layout='constrained')
    for method_i, (key, name) in enumerate(LORENZ_METHODS):
        row = records[key]
        sample_label = f"{name} (N={row['eval_trajectories']}, M={row['metric_particles']})"
        for metric_i, metric in enumerate(['rmse_all', 'rmse_obs', 'rmse_unobs']):
            x = metric_i + (method_i - 1) * .24
            axes[0].bar(x, float(row[metric]), width=.21, color=COLORS[key],
                        label=sample_label if metric_i == 0 else None)
        axes[1].scatter(float(row['mciw_all']), 100*float(row['coverage_90']),
                        color=COLORS[key], s=60, zorder=3)
    axes[0].set_xticks([0, 1, 2], ['All states', 'Observed states', 'Unobserved states'])
    axes[0].set(title='Lorenz–96: GMM3 observation noise', ylabel='RMSE', ylim=(0, .98))
    axes[0].legend(frameon=False, fontsize=7.2, loc='upper left')
    axes[1].axhline(90, color='#777777', ls='--', lw=1)
    axes[1].text(.97, .405, 'Nominal 90%', transform=axes[1].transAxes,
                 ha='right', va='bottom', color='#555555', fontsize=8)
    axes[1].set(xlabel='Mean 90% interval width', ylabel='Coverage (%)', ylim=(83, 100),
                xlim=(0, 3.2), title='Coverage and interval width')
    fig.savefig(PAPER / 'figures/lorenz96_comparison.pdf', bbox_inches='tight'); plt.close(fig)
    draw_model_overview()
    print('Built 3 tables and 2 figures from frozen evidence (3 Lorenz--96 GMM3 records).')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--refresh', action='store_true', help='Refresh snapshots from repository artifacts.')
    args = parser.parse_args()
    if args.refresh:
        freeze()
    build()
